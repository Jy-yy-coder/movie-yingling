# ---------------- 四维 → 五维 DNA 映射（可调常量） ----------------
# 四维总和恒为 36（12 题 × 3 分），PHI 高则 SEN 低，节奏自然偏低，无需负权。
WEIGHTS = {
    "剧情": {"RES": 0.10, "SEN": 0.10, "NAR": 0.45, "PHI": 0.45},  # 叙事解析+哲思 → 剧情深度
    "演技": {"RES": 0.35, "SEN": 0.05, "NAR": 0.50, "PHI": 0.10},  # 角色共情+细品表演
    "情感": {"RES": 0.85, "SEN": 0.05, "NAR": 0.00, "PHI": 0.10},  # 情感共鸣为主
    "视听": {"RES": 0.05, "SEN": 0.85, "NAR": 0.10, "PHI": 0.00},  # 感官冲击为主
    "节奏": {"RES": 0.10, "SEN": 0.70, "NAR": 0.20, "PHI": 0.00},  # 刺激爽快→快节奏
}


def _option(answers_item: dict) -> dict | None:
    """按 {q: 题号, o: 选项号} 安全取选项，非法输入返回 None。"""
    try:
        qi, oi = int(answers_item["q"]), int(answers_item["o"])
        return QUIZ[qi]["opts"][oi]
    except (KeyError, IndexError, TypeError, ValueError):
        return None


def accumulate(answers: list[dict]) -> dict:
    """累计四维原始分（每维 0-36，总和 36）。"""
    dims = {k: 0 for k in QUIZ_DIMS}
    for a in answers:
        o = _option(a)
        if o:
            dims[o["dim"]] = dims.get(o["dim"], 0) + o["score"]
    return dims


def _scale(points: float) -> int:
    """加权分 → DNA 分值：9 分（均衡）≈68，强项趋近 96，下限 40。"""
    return int(min(96, max(40, 40 + points / 18 * 56)))


def compute_dna(answers: list[dict]) -> dict:
    """答题结果 → 五维 DNA 画像（0-100）。"""
    dims = accumulate(answers)
    return {d: _scale(sum(w * dims[k] for k, w in WEIGHTS[d].items())) for d in WEIGHTS}


def collect_keywords(answers: list[dict], limit: int = 6) -> list[str]:
    """收集所选选项的标签，按出现次数降序去重，取前 limit 个。"""
    counts: dict[str, int] = {}
    for a in answers:
        o = _option(a)
        if o:
            for t in o.get("tags") or []:
                counts[t] = counts.get(t, 0) + 1
    return [t for t, _ in sorted(counts.items(), key=lambda x: -x[1])[:limit]]
